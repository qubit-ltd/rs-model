//! Persisted outputs produced while an AI engine processes an attachment.

use chrono::DateTime;
use chrono::Utc;
use qubit_id::Id;
use serde::Deserialize;

use qubit_model_derive::Model;
use qubit_redact_derive::Redact;

use crate::ai::AiResultType;
use crate::upload::Attachment;

/// Output from a named AI engine for one uploaded attachment.
#[derive(Model, Redact, Clone, Deserialize, PartialEq)]
#[redact(debug, display, serde)]
pub struct AiResult {
    /// Database identifier; its default value means this result is not persisted.
    #[model(identifier)]
    #[model(opaque)]
    pub id: Id,

    /// Semantic kind of content generated by the engine.
    #[model(index)]
    pub r#type: AiResultType,

    /// Identifier of the [`Attachment`] supplied to the engine.
    #[model(reference(target = Attachment, target_field = id), opaque)]
    pub attachment_id: Id,

    /// Content returned by the engine in the language declared below.
    pub content: String,

    /// ISO 639-1 code for the generated content's language.
    #[model(index, text(min_chars = 1, max_chars = 16))]
    pub language: String,

    /// ISO 639-1 code for the input language, or `None` when it is unknown or irrelevant.
    #[model(index, text(min_chars = 1, max_chars = 16))]
    pub original_language: Option<String>,

    /// Provider or engine name that generated this result.
    #[model(index, text(min_chars = 1, max_chars = 128))]
    pub engine_name: String,

    /// Version of the named engine used for processing.
    #[model(index, text(min_chars = 1, max_chars = 64))]
    pub engine_version: String,

    /// UTC processing start instant, stored with millisecond precision.
    #[model(index, time(precision = millisecond, normalization = utc))]
    pub process_start_time: DateTime<Utc>,

    /// UTC processing completion instant, stored with millisecond precision.
    #[model(index, time(precision = millisecond, normalization = utc))]
    pub process_end_time: DateTime<Utc>,

    /// UTC record-creation instant, stored with second precision.
    #[model(index, time(precision = second, normalization = utc))]
    pub create_time: DateTime<Utc>,

    /// UTC instant of the latest change, or `None` if the result was never updated.
    #[model(index, time(precision = second, normalization = utc))]
    pub modify_time: Option<DateTime<Utc>>,

    /// UTC soft-deletion instant, or `None` while the result remains active.
    #[model(index, time(precision = second, normalization = utc))]
    pub delete_time: Option<DateTime<Utc>>,
}
